import Foundation

// ============================================================
//  LoRA Training data model — pure Foundation (no engine import) so the
//  persistence layer stays decoupled from Flux2Core types, exactly like
//  `Generation`. Two levels, mirroring FluxForge's "atelier":
//
//    Workshop  — a reusable concept container (name, trigger, description,
//                the image set). Edited freely.
//    TrainingRun — an IMMUTABLE snapshot "forged" from a Workshop: it freezes
//                the trigger + image/caption set + every hyperparameter at
//                forge time, then carries the live run state. Named "Run" (the
//                UI calls it a "Session") to avoid clashing with the engine's
//                own `Flux2Core.TrainingSession` controller type.
// ============================================================

// MARK: - Concept

/// What a Workshop trains. Drives DOP (prior-preservation) recommendation and
/// the default preservation-class word.
enum ConceptType: String, Codable, Sendable, CaseIterable, Identifiable {
    case person
    case pet
    case object
    case style

    var id: String { rawValue }

    var label: String {
        switch self {
        case .person: return "Person"
        case .pet:    return "Pet / animal"
        case .object: return "Object / product"
        case .style:  return "Art style"
        }
    }

    /// Differential Output Preservation preserves a whole CLASS (e.g. "a person") while learning one
    /// specific instance — valuable for people and animals so the class doesn't collapse into your
    /// subject. A unique object/product or an art style don't need it (matches FluxForge's analysis).
    var recommendsDOP: Bool { self == .person || self == .pet }

    /// Default class word that replaces the trigger in the preservation loss.
    var dopClass: String {
        switch self {
        case .person: return "person"
        case .pet:    return "animal"
        case .object: return "object"
        case .style:  return "object"
        }
    }
}

/// Where a caption came from — drives the per-image badge in the caption editor.
enum CaptionSource: String, Codable, Sendable {
    case none      // not captioned yet
    case manual    // typed by the user
    case auto      // generated by the Qwen3.5 VLM
    case sidecar   // picked up from a sibling .txt
}

/// One dataset image inside a Workshop: a file copied into the workshop's images
/// dir + its caption. The trigger word is NOT stored here — the engine prepends
/// it at train time.
struct TrainingImageRef: Codable, Identifiable, Sendable, Hashable {
    let id: UUID
    var fileName: String          // relative to the Workshop's imagesDir
    var caption: String
    var captionSource: CaptionSource

    init(id: UUID = UUID(), fileName: String, caption: String = "", captionSource: CaptionSource = .none) {
        self.id = id
        self.fileName = fileName
        self.caption = caption
        self.captionSource = captionSource
    }
}

// MARK: - Workshop

/// A reusable training concept. Sessions are forged from it; editing it later
/// does NOT change already-forged runs (snapshot-on-forge).
struct Workshop: Codable, Identifiable, Sendable, Hashable {
    let id: UUID
    var name: String
    var conceptDescription: String       // AI-analyzed → recommends trigger + params
    var triggerWord: String              // single word, no spaces
    var conceptType: ConceptType
    var coverImageFileName: String?      // a chosen image used as the card cover / VLM eval ref
    /// Custom VLM instruction for auto-captioning (sent as the system prompt). nil/empty → the
    /// concept-type preset (`DescribeService.captionInstruction(for:)`). Optional so workshops
    /// persisted before this field keep decoding.
    var captionInstruction: String?
    var images: [TrainingImageRef]
    let createdAt: Date
    var updatedAt: Date

    init(
        id: UUID = UUID(),
        name: String,
        conceptDescription: String = "",
        triggerWord: String = "",
        conceptType: ConceptType = .object,
        coverImageFileName: String? = nil,
        captionInstruction: String? = nil,
        images: [TrainingImageRef] = [],
        createdAt: Date = Date(),
        updatedAt: Date = Date()
    ) {
        self.id = id
        self.name = name
        self.conceptDescription = conceptDescription
        self.triggerWord = triggerWord
        self.conceptType = conceptType
        self.coverImageFileName = coverImageFileName
        self.captionInstruction = captionInstruction
        self.images = images
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }

    /// On-disk folder that holds this workshop's imported images.
    var imagesDir: URL {
        AppPaths.trainingWorkshopsDir.appendingPathComponent(id.uuidString, isDirectory: true)
            .appendingPathComponent("images", isDirectory: true)
    }

    func imageURL(_ ref: TrainingImageRef) -> URL {
        imagesDir.appendingPathComponent(ref.fileName)
    }
}

// MARK: - Training parameters (frozen into a Run)

/// A validation prompt previewed during training. With DOP on, the form requires
/// at least one WITH the trigger and one WITHOUT. A literal `[trigger]` in the text places
/// the trigger word mid-sentence instead (resolved app-side at train time; the engine
/// prepend is turned off for that prompt — same convention as Generate prompts).
struct ValidationPrompt: Codable, Identifiable, Sendable, Hashable {
    let id: UUID
    var prompt: String
    var applyTrigger: Bool
    /// Per-prompt seed override; nil → the run-level `validationSeed`. Optional so prompts
    /// persisted before this field keep decoding.
    var seed: UInt64?

    init(id: UUID = UUID(), prompt: String, applyTrigger: Bool = true, seed: UInt64? = nil) {
        self.id = id
        self.prompt = prompt
        self.applyTrigger = applyTrigger
        self.seed = seed
    }
}

/// Timestep-sampling strategy. Our OWN Codable enum (not the engine type) so persisted runs
/// can't break if the engine renames a raw value; Chunk 2 maps it to the engine's
/// `SimpleLoRAConfig.TimestepSamplingMode` explicitly. The case set matches that enum exactly
/// ({uniform, content, style, balanced} — the GUI path has no logit-normal / flux-shift).
enum TimestepSamplingChoice: String, Codable, Sendable, CaseIterable {
    case uniform, content, style, balanced
}

/// Loss-weighting strategy. Own Codable enum for the same reason. Maps to
/// `SimpleLoRAConfig.LossWeightingMode` ({none, bellShaped}) in Chunk 2.
enum LossWeightingChoice: String, Codable, Sendable, CaseIterable {
    case none, bellShaped
}

/// Every hyperparameter, captured at forge time. Maps onto the engine's `SimpleLoRAConfig`
/// (the GUI training path via `TrainingSession.start`) PLUS the latent-caching prep step.
/// `tier` is a `ModelTier.rawValue` string for decoupling.
struct TrainingParams: Codable, Sendable, Hashable {
    var tier: String                    // ModelTier.rawValue — "klein4B" / "klein9B"
    var rank: Int                       // SimpleLoRAConfig.rank
    var alpha: Float                    // SimpleLoRAConfig.alpha
    var learningRate: Float             // SimpleLoRAConfig.learningRate
    var weightDecay: Float              // SimpleLoRAConfig.weightDecay
    var maxSteps: Int                   // SimpleLoRAConfig.maxSteps
    var batchSize: Int                  // SimpleLoRAConfig.batchSize
    var gradientAccumulationSteps: Int  // SimpleLoRAConfig.gradientAccumulationSteps (effective batch = batch × accum)
    /// Resolution used when PRE-ENCODING latents — NOT a SimpleLoRAConfig field. Chunk 3 must pass
    /// this as the `maxResolution:` argument to `prepareTrainingDataMemoryOptimized`, or the cap is
    /// silently ignored and full-res images OOM during backprop.
    var maxResolution: Int
    var saveEveryNSteps: Int            // SimpleLoRAConfig.saveEveryNSteps
    var timestepSampling: TimestepSamplingChoice
    var lossWeighting: LossWeightingChoice
    var gradientCheckpointing: Bool     // SimpleLoRAConfig.gradientCheckpointing
    // Differential Output Preservation (SimpleLoRAConfig.dop*)
    var dopEnabled: Bool
    var dopClass: String
    var dopMultiplier: Float
    // Validation previews (SimpleLoRAConfig.validation*)
    var validationEveryNSteps: Int
    var validationSeed: UInt64
    var validationPrompts: [ValidationPrompt]
    /// Rolling checkpoint retention: keep the HEAVY files (weights + optimizer state) of only the
    /// last N checkpoints as the run progresses; every checkpoint's validation PNGs stay, and the
    /// published / best-loss checkpoints are never pruned. nil = keep everything (the default).
    /// Optional so runs persisted before this field keep decoding.
    var keepLastCheckpoints: Int? = nil
    /// Mirror (flip-X) augmentation at forge time: the frozen dataset gets a horizontally
    /// mirrored copy of every image (same caption), doubling the training views. Never for
    /// faces, text or logos. nil/false = off. Optional for old-JSON compatibility.
    var flipAugment: Bool? = nil

    /// Engine-aligned defaults for a tier + concept (see SimpleLoRAConfig defaults).
    static func defaults(tier: String, conceptType: ConceptType, triggerWord: String) -> TrainingParams {
        return TrainingParams(
            tier: tier,
            rank: 32,
            alpha: 32,
            learningRate: 1e-4,
            weightDecay: 1e-4,
            // Engine author's canonical SUBJECT recipe (cat_toy_klein4b.yaml + docs/examples/TRAINING_GUIDE.md):
            // ~250 steps is "sufficient for subject LoRAs" (his run: best loss @ step 244, ~75 min) — 2000
            // overshoots and risks memorizing a generic shape + washing out the trigger. 512 is his reliable
            // resolution ceiling (768 fits but is much slower on the 32 GB M4). Save often so several mid-run
            // checkpoints exist to hand-pick (the final / lowest-loss one is often NOT the best).
            maxSteps: 300,
            batchSize: 1,
            gradientAccumulationSteps: 1,
            maxResolution: 512,
            saveEveryNSteps: 100,
            timestepSampling: .balanced,
            lossWeighting: .bellShaped,
            // MANDATORY on both tiers — without it the 4B training graph OOM'd to 76 GB on the 32 GB M4
            // (verified). With it, peak dropped to 22 GB. Never default this to false.
            gradientCheckpointing: true,
            dopEnabled: conceptType.recommendsDOP,
            dopClass: conceptType.dopClass,
            dopMultiplier: 1.0,
            validationEveryNSteps: 100,   // doForge re-aligns this to saveEveryNSteps at forge time
            validationSeed: 42,
            validationPrompts: []
        )
    }
}

// MARK: - Run state

enum TrainingRunStatus: String, Codable, Sendable {
    case draft          // forged but not started
    case preparing      // encoding latents + text embeddings
    case loadingModel   // loading the base transformer
    case training       // stepping
    case paused
    case completed      // finished cleanly (checkpoints ready to review)
    case failed
    case cancelled
    case published      // a chosen checkpoint was published to the LoRA library

    var isActive: Bool {
        switch self {
        case .preparing, .loadingModel, .training, .paused: return true
        default: return false
        }
    }

    var label: String {
        switch self {
        case .draft:        return "Draft"
        case .preparing:    return "Preparing…"
        case .loadingModel: return "Loading model…"
        case .training:     return "Training"
        case .paused:       return "Paused"
        case .completed:    return "Completed"
        case .failed:       return "Failed"
        case .cancelled:    return "Cancelled"
        case .published:    return "Published"
        }
    }
}

/// One saved checkpoint and its validation previews. Whether a checkpoint is "published" is
/// NOT stored here — it's derived from `TrainingRun.publishedCheckpointStep` (single source of
/// truth) so the publish signals can't drift across three places.
struct TrainingCheckpoint: Codable, Identifiable, Sendable, Hashable {
    var id: Int { step }
    let step: Int
    var dirName: String                  // relative to the Run's outputDir
    var validationImageNames: [String]   // relative to the Run's outputDir (resolved from the engine's absolute URLs)

    init(step: Int, dirName: String, validationImageNames: [String] = []) {
        self.step = step
        self.dirName = dirName
        self.validationImageNames = validationImageNames
    }
}

/// Live run telemetry, updated from the engine observer.
struct TrainingRuntime: Codable, Sendable, Hashable {
    var currentStep: Int
    var totalSteps: Int
    var lossHistory: [Float]             // sampled per logged step
    var checkpoints: [TrainingCheckpoint]
    var message: String
    var startedAt: Date?
    var finishedAt: Date?
    /// Disk bytes freed by rolling checkpoint retention (see `TrainingParams.keepLastCheckpoints`).
    /// Optional so runtimes persisted before this field keep decoding.
    var reclaimedBytes: Int64? = nil

    init(totalSteps: Int) {
        self.currentStep = 0
        self.totalSteps = totalSteps
        self.lossHistory = []
        self.checkpoints = []
        self.message = ""
        self.startedAt = nil
        self.finishedAt = nil
    }

    var progress: Double {
        totalSteps > 0 ? min(1, Double(currentStep) / Double(totalSteps)) : 0
    }
}

// MARK: - TrainingRun (immutable snapshot + live state)

/// An immutable training run forged from a Workshop. The inputs (trigger, image
/// set, params) are frozen; `status` and `runtime` evolve as it trains.
struct TrainingRun: Codable, Identifiable, Sendable, Hashable {
    let id: UUID
    let workshopId: UUID
    var name: String
    let triggerWord: String
    let conceptType: ConceptType
    let imageCount: Int                   // frozen dataset is copied to datasetDir at forge
    /// Frozen at forge — with ONE designed exception: "Extend training" raises `maxSteps` on a
    /// finished run so it can resume from its last checkpoint (rank/alpha/LR stay frozen; the
    /// engine's checkpoint-compatibility check verifies those, not the step target).
    var params: TrainingParams
    var status: TrainingRunStatus
    var runtime: TrainingRuntime
    /// Single source of truth for publish state: a checkpoint is published iff its `step` equals
    /// this. `status == .published` is presentation-only and is kept in sync with this value.
    var publishedCheckpointStep: Int?
    let createdAt: Date

    init(
        id: UUID = UUID(),
        workshopId: UUID,
        name: String,
        triggerWord: String,
        conceptType: ConceptType,
        imageCount: Int,
        params: TrainingParams,
        status: TrainingRunStatus = .draft,
        publishedCheckpointStep: Int? = nil,
        createdAt: Date = Date()
    ) {
        self.id = id
        self.workshopId = workshopId
        self.name = name
        self.triggerWord = triggerWord
        self.conceptType = conceptType
        self.imageCount = imageCount
        self.params = params
        self.status = status
        self.runtime = TrainingRuntime(totalSteps: params.maxSteps)
        self.publishedCheckpointStep = publishedCheckpointStep
        self.createdAt = createdAt
    }

    /// Engine output directory — passed to `TrainingSession(outputDirectory:)`.
    /// Holds checkpoints, validation images and the trained adapter.
    var outputDir: URL {
        AppPaths.trainingRunsDir.appendingPathComponent(id.uuidString, isDirectory: true)
    }

    /// Frozen copy of the dataset (images + sibling .txt captions) used for this run.
    var datasetDir: URL {
        outputDir.appendingPathComponent("dataset", isDirectory: true)
    }

    var tier: ModelTier { ModelTier(rawValue: params.tier) ?? .klein4B }
}
